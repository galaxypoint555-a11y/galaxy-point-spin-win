-- Galaxy Point: secure CMS backing tables for existing GitHub Pages website.
-- Run in a Supabase project SQL Editor AFTER project creation.
-- Do not put a service_role key into the website or panel.
create table if not exists public.gp_admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','editor')),
  created_at timestamptz not null default now()
);
create table if not exists public.gp_site_content (
  id text primary key,
  hero_video_url text,
  hero_heading text,
  hero_subheading text,
  category_images jsonb not null default '{}'::jsonb,
  banner_images jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);
insert into public.gp_site_content (id) values ('main') on conflict (id) do nothing;
create table if not exists public.gp_products (
  id bigint generated by default as identity primary key,
  name text not null,
  brand text not null default '',
  details text not null default '',
  category text not null check (category in ('iPhone','Samsung','Laptops','Accessories','Other')),
  price numeric(12,2) check (price>=0),
  stock integer not null default 0 check (stock>=0),
  photo_url text,
  is_published boolean not null default true,
  position integer not null default 0,
  updated_at timestamptz not null default now()
);
create or replace function public.gp_is_editor()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.gp_admin_users where user_id = (select auth.uid()))
$$;
revoke all on function public.gp_is_editor() from public;
grant execute on function public.gp_is_editor() to authenticated;
alter table public.gp_admin_users enable row level security;
alter table public.gp_site_content enable row level security;
alter table public.gp_products enable row level security;
grant select on public.gp_site_content, public.gp_products to anon;
grant select, insert, update, delete on public.gp_site_content, public.gp_products to authenticated;
grant select on public.gp_admin_users to authenticated;
grant usage, select on sequence public.gp_products_id_seq to authenticated;
drop policy if exists gp_admin_self on public.gp_admin_users;
create policy gp_admin_self on public.gp_admin_users for select to authenticated using (user_id=(select auth.uid()));
drop policy if exists gp_site_public_read on public.gp_site_content;
create policy gp_site_public_read on public.gp_site_content for select to anon, authenticated using (true);
drop policy if exists gp_site_admin_insert on public.gp_site_content;
create policy gp_site_admin_insert on public.gp_site_content for insert to authenticated with check ((select public.gp_is_editor()));
drop policy if exists gp_site_admin_update on public.gp_site_content;
create policy gp_site_admin_update on public.gp_site_content for update to authenticated
  using ((select public.gp_is_editor())) with check ((select public.gp_is_editor()));
drop policy if exists gp_products_read on public.gp_products;
create policy gp_products_read on public.gp_products for select to anon, authenticated
  using (is_published or (select public.gp_is_editor()));
drop policy if exists gp_products_insert on public.gp_products;
create policy gp_products_insert on public.gp_products for insert to authenticated with check ((select public.gp_is_editor()));
drop policy if exists gp_products_update on public.gp_products;
create policy gp_products_update on public.gp_products for update to authenticated
  using ((select public.gp_is_editor())) with check ((select public.gp_is_editor()));
drop policy if exists gp_products_delete on public.gp_products;
create policy gp_products_delete on public.gp_products for delete to authenticated using ((select public.gp_is_editor()));
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('gp-site-media','gp-site-media',true,104857600,ARRAY['image/jpeg','image/png','image/webp','video/mp4','video/webm'])
on conflict (id) do nothing;
drop policy if exists gp_media_public_read on storage.objects;
create policy gp_media_public_read on storage.objects for select to anon, authenticated using (bucket_id='gp-site-media');
drop policy if exists gp_media_admin_upload on storage.objects;
create policy gp_media_admin_upload on storage.objects for insert to authenticated with check
  (bucket_id='gp-site-media' and (select public.gp_is_editor()));
drop policy if exists gp_media_admin_update on storage.objects;
create policy gp_media_admin_update on storage.objects for update to authenticated
  using (bucket_id='gp-site-media' and (select public.gp_is_editor()))
  with check (bucket_id='gp-site-media' and (select public.gp_is_editor()));
drop policy if exists gp_media_admin_delete on storage.objects;
create policy gp_media_admin_delete on storage.objects for delete to authenticated
  using (bucket_id='gp-site-media' and (select public.gp_is_editor()));
